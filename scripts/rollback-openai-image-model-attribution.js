#!/usr/bin/env node

const fs = require('fs')
const Redis = require('ioredis')
const config = require('../config/config')

function parseArgs(argv) {
  const args = {
    file: '',
    yes: false,
    batchSize: 100
  }

  for (let i = 2; i < argv.length; i++) {
    const arg = argv[i]
    const next = argv[i + 1]
    if (arg === '--yes') {
      args.yes = true
    } else if (arg.startsWith('--file=')) {
      args.file = arg.slice('--file='.length)
    } else if (arg === '--file') {
      args.file = next
      i++
    } else if (arg.startsWith('--batch-size=')) {
      args.batchSize = Number.parseInt(arg.slice('--batch-size='.length), 10)
    } else if (arg === '--batch-size') {
      args.batchSize = Number.parseInt(next, 10)
      i++
    } else if (arg === '--help' || arg === '-h') {
      printHelp()
      process.exit(0)
    } else {
      throw new Error(`Unknown argument: ${arg}`)
    }
  }

  args.batchSize = Number.isFinite(args.batchSize) && args.batchSize > 0 ? args.batchSize : 100
  return args
}

function printHelp() {
  console.log(`Usage:
  node scripts/rollback-openai-image-model-attribution.js --file <rollback.json> --yes

Restores request detail model fields, usage record entries, and reverse aggregation deltas
from a rollback file generated by fix-openai-image-model-attribution.js --apply.
`)
}

function restoreOptionalField(record, field, value) {
  if (value === undefined) {
    delete record[field]
  } else {
    record[field] = value
  }
}

async function rollbackRequestDetail(redis, entry) {
  const raw = await redis.get(entry.key)
  if (!raw) {
    return false
  }

  const record = JSON.parse(raw)
  const ttl = await redis.ttl(entry.key)
  record.model = entry.originalFields.model
  restoreOptionalField(record, 'correctedFromModel', entry.originalFields.correctedFromModel)
  restoreOptionalField(record, 'correctedAt', entry.originalFields.correctedAt)
  restoreOptionalField(record, 'correctionReason', entry.originalFields.correctionReason)
  await redis.set(entry.key, JSON.stringify(record))
  if (ttl > 0) {
    await redis.expire(entry.key, ttl)
  }
  return true
}

async function rollbackUsageRecord(redis, entry) {
  const entries = await redis.lrange(entry.key, 0, 250)
  for (let index = 0; index < entries.length; index++) {
    let record
    try {
      record = JSON.parse(entries[index])
    } catch (_error) {
      continue
    }

    if (record.requestId === entry.requestId) {
      await redis.lset(entry.key, index, JSON.stringify(entry.originalRecord))
      return true
    }
  }
  return false
}

async function applyDeltas(redis, deltas, batchSize) {
  for (let i = 0; i < deltas.length; i += batchSize) {
    const batch = deltas.slice(i, i + batchSize)
    const pipeline = redis.pipeline()
    for (const delta of batch) {
      if (delta.op === 'hincrby') {
        pipeline.hincrby(delta.key, delta.field, delta.value)
      }
    }
    await pipeline.exec()
    console.log(`Rollback deltas ${Math.min(i + batch.length, deltas.length)}/${deltas.length}`)
  }
}

async function main() {
  const args = parseArgs(process.argv)
  if (!args.file) {
    throw new Error('--file is required')
  }
  if (!args.yes) {
    throw new Error('Rollback requires --yes')
  }

  const rollback = JSON.parse(fs.readFileSync(args.file, 'utf8'))
  const redis = new Redis({
    ...config.redis,
    tls: config.redis.enableTLS ? {} : undefined
  })

  const result = {
    requestDetailsRestored: 0,
    requestDetailsMissing: 0,
    usageRecordsRestored: 0,
    usageRecordsMissing: 0,
    deltaCount: rollback.deltas?.length || 0
  }

  try {
    await redis.ping()
    for (const entry of rollback.requestDetails || []) {
      if (await rollbackRequestDetail(redis, entry)) {
        result.requestDetailsRestored += 1
      } else {
        result.requestDetailsMissing += 1
      }
    }

    for (const entry of rollback.usageRecords || []) {
      if (await rollbackUsageRecord(redis, entry)) {
        result.usageRecordsRestored += 1
      } else {
        result.usageRecordsMissing += 1
      }
    }

    await applyDeltas(redis, rollback.deltas || [], args.batchSize)
    console.log(JSON.stringify(result, null, 2))
  } finally {
    redis.disconnect()
  }
}

main().catch((error) => {
  console.error(`Failed: ${error.message}`)
  process.exit(1)
})
